"""Generate bundled 9px Montserrat value font; requires Pillow."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
root = Path(__file__).resolve().parents[1]
font = ImageFont.truetype(str(root / 'components/lvgl/lvgl/scripts/built_in_font/Montserrat-Medium.ttf'), 9)
data, rows = [], []
for code in list(range(32,127)) + [176,181]:
    ch = chr(code)
    left, top, right, bottom = font.getbbox(ch, anchor='ls')
    w, h = right-left, bottom-top
    im = Image.new('L',(max(w,1),max(h,1)))
    ImageDraw.Draw(im).text((-left,-top),ch,font=font,fill=255,anchor='ls')
    values = [round(v/17) for v in im.getdata()] if w*h else []
    offset=len(data)
    data.extend((values[i]<<4) | (values[i+1] if i+1<len(values) else 0) for i in range(0,len(values),2))
    rows.append(f'{{{code},{offset},{round(font.getlength(ch))},{w},{h},{left},{-bottom}}}')
out='/* Generated by scripts/generate_small_font.py from bundled Montserrat-Medium.ttf. */\n'
out+='static const uint8_t small_bitmap[] = {\n'+','.join(map(str,data))+'};\n'
out+='static const struct {uint16_t code, offset; uint8_t advance,w,h; int8_t x,y;} small_glyphs[] = {\n'+',\n'.join(rows)+'};\n'
out+='''static bool small_glyph(const lv_font_t *font, lv_font_glyph_dsc_t *d, uint32_t code, uint32_t next)
{
    (void)font; (void)next;
    for (unsigned i=0;i<sizeof(small_glyphs)/sizeof(small_glyphs[0]);i++) {
        if(small_glyphs[i].code!=code) continue;
        memset(d,0,sizeof(*d)); d->adv_w=small_glyphs[i].advance;
        d->box_w=small_glyphs[i].w; d->box_h=small_glyphs[i].h;
        d->ofs_x=small_glyphs[i].x; d->ofs_y=small_glyphs[i].y; d->bpp=4; return true;
    }
    return false;
}
static const uint8_t *small_bitmap_get(const lv_font_t *font,uint32_t code)
{
    (void)font;
    for(unsigned i=0;i<sizeof(small_glyphs)/sizeof(small_glyphs[0]);i++)
        if(small_glyphs[i].code==code) return small_bitmap+small_glyphs[i].offset;
    return NULL;
}
const lv_font_t lv_font_montserrat_9 = {
    .get_glyph_dsc=small_glyph,.get_glyph_bitmap=small_bitmap_get,
    .line_height=13,.base_line=3,.subpx=LV_FONT_SUBPX_NONE
};
'''
(root/'main/modbus_src/lv_app_font_small.inc').write_text(out)
